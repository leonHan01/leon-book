import { build } from 'esbuild';
import { cp, mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const destination = path.resolve(here, '../Sources/LeonBook/Whiteboard');
const output = await mkdtemp(path.join(tmpdir(), 'leon-whiteboard-build-'));
await build({
  absWorkingDir: here, entryPoints: ['editor.jsx'], outfile: path.join(output, 'editor.js'),
  bundle: true, minify: true, format: 'iife', platform: 'browser', target: ['safari16'],
  conditions: ['production'],
  define: { 'process.env.NODE_ENV': '"production"', 'process.env.IS_PREACT': '"false"', 'import.meta.url': '"leonboard://app/editor.js"' },
  loader: { '.woff2': 'file', '.woff': 'file', '.ttf': 'file' },
  legalComments: 'eof', logLevel: 'info',
});
await cp(path.join(here, 'index.html'), path.join(output, 'index.html'));
await cp(path.join(here, 'node_modules/@excalidraw/excalidraw/dist/prod/fonts'), output, { recursive: true });

// Ship license texts alongside the exact compiled dependencies, including font
// licenses. No network access or npm installation is needed when running Swift.
const lock = JSON.parse(await readFile(path.join(here, 'package-lock.json'), 'utf8'));
const notices = ['LeonBook embeds Excalidraw 0.18.1. Generated by macos/Whiteboard/build.mjs.\n'];
for (const [relative, info] of Object.entries(lock.packages)) {
  if (!relative || info.dev) continue;
  const directory = path.join(here, relative);
  let entries;
  try { entries = await readdir(directory); } catch { continue; }
  for (const filename of entries.filter(name => /^(license|licence|notice|copying)(\.|$)/i.test(name))) {
    try { notices.push(`\n--- ${relative} ${info.version} / ${filename} ---\n${await readFile(path.join(directory, filename), 'utf8')}`); } catch {}
  }
}
await writeFile(path.join(output, 'THIRD-PARTY-NOTICES.txt'), notices.join('\n'));
await cp(path.join(here, 'licenses'), path.join(output, 'licenses'), { recursive: true });
// A failed bundle must leave the previously shipped runtime intact.
await rm(destination, { recursive: true, force: true });
await cp(output, destination, { recursive: true });
await rm(output, { recursive: true, force: true });
